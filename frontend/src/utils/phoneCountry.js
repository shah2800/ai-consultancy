const SORTED_PREFIXES = Object.keys(PREFIX_TO_LABEL)
  .map(Number)
  .sort((a, b) => String(b).length - String(a).length);

export function inferPhoneOrigin(rawPhone) {
  const digits = String(rawPhone || "").replace(/\D/g, "");
  if (digits.length < 8 || digits.length > 15) return null;

  for (const prefix of SORTED_PREFIXES) {
    const p = String(prefix);
    if (digits.startsWith(p)) {
      const label = PREFIX_TO_LABEL[prefix];
      if (!label) continue;
      return {
        iso: PREFIX_TO_ISO[prefix] || null,
        country: label,
        dialDisplay: `+${p}`,
        prefix: p,
        nationalNumber: digits.slice(p.length) || null,
      };
    }
  }
  return null;
}
